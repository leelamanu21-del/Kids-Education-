  fun lettersForMode(mode: LearningMode): List<PhonicsLetter> =
    when (mode) {
      LearningMode.SATPIN -> letters.sortedBy { it.satpinOrder }
      LearningMode.AZ -> letters.sortedBy { it.azOrder }
    }

  fun findByLetter(letter: String): PhonicsLetter? =
    letters.firstOrNull { it.letter.equals(letter, ignoreCase = true) }

  fun quizOptionsFor(target: PhonicsLetter): List<PhonicsLetter> {
    val distractors =
      letters
        .filter { it.letter != target.letter }
        .sortedBy { kotlin.math.abs(it.satpinOrder - target.satpinOrder) }
        .take(2)
    return (listOf(target) + distractors).sortedBy { it.azOrder }
  }

  fun hindiSoundTag(letter: String): String =
